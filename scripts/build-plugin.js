#!/usr/bin/env node
// Builds src/plugin/index.js, the single-file plugin script shipped in the
// pbw, from src/plugin-src/main.js and the modules it requires. ES5.
//
// The plugin host evaluates one script with no require() and no bundler
// (the SDK's plugin packaging copies plugin.script into the pbw unchanged),
// so the modules are concatenated into one IIFE with a tiny module table.
// XMLHttpRequest, setTimeout and clearTimeout are bound in bundle scope
// (see src/plugin-src/xhr_shim.js), so the shared modules run unchanged and
// the runtime's globals are never replaced.
//
// The host's fetch and timers are probed outside the IIFE, each inside its own
// try/catch, and passed in. On Android the plugin runs in a WebView whose
// LOCKDOWN_JS replaces setTimeout, clearTimeout, XMLHttpRequest, window, self
// and more with getters that THROW (mobileapp libpebble3
// js/JsEngine.android.kt), and `typeof` does not guard against a throwing
// getter. evaluateJavascript swallows the exception, so an unguarded probe
// silently leaves no source handler registered ("no source handler
// registered", seen on Pebble app 1.16.0.5).
//
// Usage: node scripts/build-plugin.js          (writes src/plugin/index.js)
//        node scripts/build-plugin.js --check  (exit 1 if it is out of date)

var fs = require('fs');
var path = require('path');

var ROOT = path.join(__dirname, '..');
var SRC = path.join(ROOT, 'src');
var OUT = path.join(SRC, 'plugin', 'index.js');
var ENTRY = 'plugin-src/main';
var SHIM = 'plugin-src/xhr_shim';

/**
 * Resolve a require() path relative to the requiring module.
 * @param {string} from - Module id (path under src/, no extension)
 * @param {string} request - require() argument
 * @returns {string} Module id
 */
function resolve(from, request) {
    return path.posix.normalize(path.posix.join(path.posix.dirname(from), request)).replace(/\.js$/, '');
}

/**
 * Collect the entry module and everything it requires, depth first.
 * @param {string} id - Module id
 * @param {Object} seen - id -> source
 * @param {Array} order - Module ids in load order
 */
function collect(id, seen, order) {
    if (seen[id] !== undefined) return;
    var src = fs.readFileSync(path.join(SRC, id + '.js'), 'utf8');
    seen[id] = src;
    var re = /require\(\s*'([^']+)'\s*\)/g;
    var m;
    while ((m = re.exec(src)) !== null) {
        if (m[1].charAt(0) !== '.') throw new Error(id + ': only relative requires can be bundled: ' + m[1]);
        collect(resolve(id, m[1]), seen, order);
    }
    order.push(id);
}

/**
 * Build the bundle text.
 * @returns {string} Contents for src/plugin/index.js
 */
function build() {
    var seen = {};
    var order = [];
    collect(SHIM, seen, order);
    collect(ENTRY, seen, order);

    var out = [];
    out.push('// GENERATED by scripts/build-plugin.js from src/plugin-src/main.js. Do not edit.');
    out.push('// Modules: ' + order.join(', '));
    out.push('(function (__hostFetch, __hostSetTimeout, __hostClearTimeout) {');
    out.push('var __defs = {};');
    out.push('var __cache = {};');
    out.push('function __require(from, request) {');
    out.push('    var parts = from.split(\'/\');');
    out.push('    parts.pop();');
    out.push('    var segs = request.replace(/\\.js$/, \'\').split(\'/\');');
    out.push('    for (var i = 0; i < segs.length; i++) {');
    out.push('        if (segs[i] === \'..\') parts.pop();');
    out.push('        else if (segs[i] !== \'.\') parts.push(segs[i]);');
    out.push('    }');
    out.push('    return __load(parts.join(\'/\'));');
    out.push('}');
    out.push('function __load(id) {');
    out.push('    if (__cache[id]) return __cache[id].exports;');
    out.push('    if (!__defs[id]) throw new Error(\'plugin bundle: no module \' + id);');
    out.push('    var module = { exports: {} };');
    out.push('    __cache[id] = module;');
    out.push('    __defs[id](module, module.exports, function (r) { return __require(id, r); });');
    out.push('    return module.exports;');
    out.push('}');
    order.forEach(function(id) {
        out.push('__defs[' + JSON.stringify(id) + '] = function (module, exports, require) {');
        out.push(seen[id].replace(/\s+$/, ''));
        out.push('};');
    });
    out.push('var setTimeout = __hostSetTimeout || function () { return null; };');
    out.push('var clearTimeout = __hostClearTimeout ? function (h) { if (h !== null) __hostClearTimeout(h); } : function () {};');
    out.push('try {');
    out.push('    var XMLHttpRequest = __load(' + JSON.stringify(SHIM) + ').createXHR(__hostFetch, __hostSetTimeout, __hostClearTimeout ? clearTimeout : null);');
    out.push('    __load(' + JSON.stringify(ENTRY) + ');');
    out.push('} catch (e) {');
    out.push('    // Shows as plugin> in pebble logs; without it a start-up failure is silent.');
    out.push('    console.error(\'Rat Scout plugin failed to start: \' + (e && e.stack ? e.stack : e));');
    out.push('    throw e;');
    out.push('}');
    out.push('})(');
    out.push('    (function () { try { if (typeof fetch === \'function\') return function (url, options) { return fetch(url, options); }; } catch (e) {} return function () { return Promise.reject(new TypeError(\'fetch unavailable\')); }; })(),');
    out.push('    (function () { try { if (typeof setTimeout === \'function\') return function (f, ms) { return setTimeout(f, ms); }; } catch (e) {} return null; })(),');
    out.push('    (function () { try { if (typeof clearTimeout === \'function\') return function (h) { clearTimeout(h); }; } catch (e) {} return null; })());');
    return out.join('\n') + '\n';
}

if (require.main === module) {
    var text = build();
    if (process.argv.indexOf('--check') !== -1) {
        var current = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
        if (current !== text) {
            console.error('src/plugin/index.js is out of date: run node scripts/build-plugin.js');
            process.exit(1);
        }
        console.log('src/plugin/index.js is up to date');
    } else {
        fs.mkdirSync(path.dirname(OUT), { recursive: true });
        fs.writeFileSync(OUT, text);
        console.log('wrote ' + path.relative(ROOT, OUT));
    }
}

module.exports = { build: build, OUT: OUT };
